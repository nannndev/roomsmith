// Helper to build rectangular or custom blueprints cleanly
function rectTiles(
  x0: number,
  z0: number,
  w: number,
  h: number,
  zone: RoomZoneId,
  floorMat: FloorMaterialId,
  wallMat: WallMaterialId,
): Record<string, RoomBlueprint['tiles'][string]> {
  const out: Record<string, RoomBlueprint['tiles'][string]> = {};
  for (let x = x0; x < x0 + w; x++) {
    for (let z = z0; z < z0 + h; z++) {
      out[`${x},${z}`] = { x, z, zone, floorMat, wallMat };
    }
  }
  return out;
}

