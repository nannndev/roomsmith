export function cloneBlueprint(bp: RoomBlueprint): RoomBlueprint {
  const tiles: RoomBlueprint['tiles'] = {};
  for (const [k, v] of Object.entries(bp.tiles)) {
    tiles[k] = { ...v };
  }
  const wallStyles: NonNullable<RoomBlueprint['wallStyles']> = {};
  if (bp.wallStyles) {
    for (const [k, v] of Object.entries(bp.wallStyles)) {
      wallStyles[k] = { ...v };
    }
  }
  const roomLights: NonNullable<RoomBlueprint['roomLights']> = {};
  if (bp.roomLights) {
    for (const [k, v] of Object.entries(bp.roomLights)) {
      if (v) roomLights[k] = { ...v };
    }
  }
  const customWalls = bp.customWalls ? bp.customWalls.map((w) => ({ ...w })) : [];
  const otherFloors: NonNullable<RoomBlueprint['otherFloors']> = {};
  if (bp.otherFloors) {
    for (const [k, floor] of Object.entries(bp.otherFloors)) {
      if (!floor) continue;
      const fTiles: RoomBlueprint['tiles'] = {};
      for (const [tk, tv] of Object.entries(floor.tiles || {})) {
        fTiles[tk] = { ...tv };
      }
      const fWallStyles: NonNullable<RoomBlueprint['wallStyles']> = {};
      if (floor.wallStyles) {
        for (const [wk, wv] of Object.entries(floor.wallStyles)) {
          fWallStyles[wk] = { ...wv };
        }
      }
      const fRoomLights: NonNullable<RoomBlueprint['roomLights']> = {};
      if (floor.roomLights) {
        for (const [lk, lv] of Object.entries(floor.roomLights)) {
          if (lv) fRoomLights[lk] = { ...lv };
        }
      }
      otherFloors[Number(k)] = {
        tiles: fTiles,
        interiorWalls: { ...(floor.interiorWalls || {}) },
        openings: { ...(floor.openings || {}) },
        wallStyles: fWallStyles,
        customWalls: (floor.customWalls || []).map((w) => ({ ...w })),
        furniture: (floor.furniture || []).map((f) => ({ ...f })),
        roomNames: { ...(floor.roomNames || {}) },
        roomLights: fRoomLights,
      };
    }
  }
  return {
    gridSize: bp.gridSize,
    site: bp.site ? { ...bp.site } : { ...DEFAULT_SITE_CONFIG },
    tiles,
    interiorWalls: { ...bp.interiorWalls },
    openings: { ...bp.openings },
    wallStyles,
    customWalls,
    furniture: bp.furniture.map((f) => ({ ...f })),
    roomNames: { ...(bp.roomNames || {}) },
    roomLights,
    exteriorWallMat: bp.exteriorWallMat,
    activeFloor: bp.activeFloor ?? 0,
    floorCount: bp.floorCount ?? 1,
    otherFloors,
  };
}
